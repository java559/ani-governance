#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""权威权限映射表（TSV）-> Go 映射代码（编译期固化）。

链路（两段可复现，见 docs/contracts/permission-code.md §4 与实施文档 §B8.3/§B8.4）：

  1) docs/plans/gov-auth-session-api-unification/route-map.tsv
        --(gen-management-perm-map.py)--> docs/contracts/permission-code-management-map.tsv
  2) docs/contracts/*.tsv
        --(本脚本)--> pkg/permcode/{management,capability,exempt}_gen.go

运行时不读取 TSV；服务端只 import 生成的 Go 映射。生成物不手改。

豁免表来源：route-map.tsv 中 classification ∈ {browser_auth, stream, tenant_business}
的路由，属规范 §4.1 "独立认证/会话或特殊传输入口"，不走业务码推导；对齐入口据此
把它们与"缺项"区别对待（§B4 第 1 条）。

用法：
  python scripts/permcode/gen-go-maps.py            # 写出生成物
  python scripts/permcode/gen-go-maps.py --check    # 只校验：生成物最新 + 表内/跨表一致性
退出码：0 通过；1 校验失败（文件过期、重复键、跨表冲突或 TSV 缺失）。
"""
from __future__ import annotations

import argparse
import csv
import io
import os
import subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ROUTE_MAP_TSV = os.path.join(ROOT, "docs", "plans", "gov-auth-session-api-unification", "route-map.tsv")
MANAGEMENT_TSV = os.path.join(ROOT, "docs", "contracts", "permission-code-management-map.tsv")
CAPABILITY_TSV = os.path.join(ROOT, "docs", "contracts", "permission-code-capability-map.tsv")
OUT_DIR = os.path.join(ROOT, "pkg", "permcode")
MANAGEMENT_GO = os.path.join(OUT_DIR, "management_gen.go")
CAPABILITY_GO = os.path.join(OUT_DIR, "capability_gen.go")
EXEMPT_GO = os.path.join(OUT_DIR, "exempt_gen.go")

HEADER = "// Code generated by scripts/permcode/gen-go-maps.py. DO NOT EDIT.\n"

# route-map classification -> 豁免原因（规范 §4.1：独立认证/会话或特殊传输入口等
# 不属于业务码推导范围的路由）。豁免集合 = route-map 中未出现在两张权威表里的路由。
EXEMPT_CLASSIFICATIONS = {
    "browser_auth": "独立认证/会话合同",
    "stream": "特殊传输入口",
    "tenant_business": "业务域接口（不在管理面/六域权限码范围）",
    "existing_api_domain": "既有认证/会话域接口（不在权限码范围）",
}


def rel(p):
    return os.path.relpath(p, ROOT).replace(os.sep, "/")


def read_tsv(path):
    if not os.path.isfile(path):
        raise ValueError("authoritative TSV missing: %s" % rel(path))
    with io.open(path, "r", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def management_entries():
    """(key, operation, code, source, business_module, scope_kind)。"""
    out = []
    for r in read_tsv(MANAGEMENT_TSV):
        code = r["expected_permission_code"].strip()
        if not code:
            raise ValueError("management row without expected_permission_code: %s %s"
                             % (r["method"], r["new_path"]))
        out.append(("%s %s" % (r["method"].strip(), r["new_path"].strip()),
                    r["operation"].strip(), code, r["permission_source"].strip(),
                    r["business_module"].strip() or "UNSPECIFIED", r["scope_kind"].strip()))
    return out


def capability_entries():
    """(key, code, source, business_module, scope_kind)。"""
    out = []
    for r in read_tsv(CAPABILITY_TSV):
        path = (r.get("target_path") or r.get("current_path") or "").strip()
        out.append(("%s %s" % (r["method"].strip(), path), r["permission_code"].strip(),
                    r["code_source"].strip(), r["business_module"].strip() or "UNSPECIFIED",
                    r["scope_kind"].strip()))
    return out


def exempt_entries(table_keys):
    """(key, reason)：route-map 中独立认证/特殊传输/业务域且不在两张权威表内的路由。"""
    out = []
    for r in read_tsv(ROUTE_MAP_TSV):
        classification = r["classification"].strip()
        if classification not in EXEMPT_CLASSIFICATIONS:
            continue
        path = r["new_path"].strip()
        if not path:
            continue
        k = "%s %s" % (r["method"].strip(), path)
        if k in table_keys:
            continue
        out.append((k, EXEMPT_CLASSIFICATIONS[classification]))
    return out


def check_unique(entries, key_of, label):
    seen = set()
    for e in entries:
        k = key_of(e)
        if k in seen:
            raise ValueError("duplicate %s key: %s" % (label, k))
        seen.add(k)


def route_map_keys():
    keys = set()
    for r in read_tsv(ROUTE_MAP_TSV):
        path = r["new_path"].strip()
        if path:
            keys.add("%s %s" % (r["method"].strip(), path))
    return keys


def cross_table_conflicts(mgmt, cap):
    a = {e[0]: e[2] for e in mgmt}
    b = {e[0]: e[1] for e in cap}
    return [(k, a[k], b[k]) for k in sorted(set(a) & set(b)) if a[k] != b[k]]


def go_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def format_go(content):
    """用 gofmt 规范化生成物，使"重新生成"与"磁盘上已格式化文件"逐字节一致。"""
    proc = subprocess.run(["gofmt"], input=content.encode("utf-8"),
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if proc.returncode != 0:
        raise ValueError("gofmt failed: %s" % proc.stderr.decode("utf-8", "replace"))
    return proc.stdout.decode("utf-8")


def render_management(entries):
    lines = [HEADER,
             "// 源自 %s（管理面 %d 行，生成期固化）。\n" % (rel(MANAGEMENT_TSV), len(entries)),
             "package permcode\n\n",
             "var managementOperations = map[string]expectation{\n"]
    for key, op, code, source, module, scope in sorted(entries, key=lambda e: e[0]):
        lines.append('\t"%s": {Operation: "%s", Code: "%s", Source: "%s", BusinessModule: "%s", ScopeKind: "%s"},\n'
                     % (go_escape(key), go_escape(op), go_escape(code), go_escape(source),
                        go_escape(module), go_escape(scope)))
    lines.append("}\n")
    return "".join(lines)


def render_capability(entries):
    lines = [HEADER,
             "// 源自 %s（业务域+Quota %d 行）。\n" % (rel(CAPABILITY_TSV), len(entries)),
             "package permcode\n\n",
             "var capabilityOperations = map[string]expectation{\n"]
    for key, code, source, module, scope in sorted(entries, key=lambda e: e[0]):
        lines.append('\t"%s": {Code: "%s", Source: "%s", BusinessModule: "%s", ScopeKind: "%s"},\n'
                     % (go_escape(key), go_escape(code), go_escape(source),
                        go_escape(module), go_escape(scope)))
    lines.append("}\n")
    return "".join(lines)


def render_exempt(entries):
    lines = [HEADER,
             "// 源自 %s 的 browser_auth/stream/tenant_business 路由（独立认证/特殊传输/业务域）。\n" % rel(ROUTE_MAP_TSV),
             "package permcode\n\n",
             "var exemptReasons = map[string]string{\n"]
    for key, reason in sorted(entries, key=lambda e: e[0]):
        lines.append('\t"%s": "%s",\n' % (go_escape(key), go_escape(reason)))
    lines.append("}\n")
    return "".join(lines)


def sync(path, content, check):
    # 生成物必须 gofmt 对齐：CI 的 changed-file format 检查只跑 gofmt -l，
    # 若生成器产出未对齐文本，一次重生成就会让生成物与磁盘既有文件不一致。
    content = format_go(content)
    if check:
        current = ""
        if os.path.isfile(path):
            with io.open(path, "r", encoding="utf-8", newline="") as f:
                current = f.read()
        if current != content:
            raise ValueError("generated file out of date: %s（请重跑 gen-go-maps.py）" % rel(path))
        return
    if not os.path.isdir(OUT_DIR):
        os.makedirs(OUT_DIR)
    with io.open(path, "w", encoding="utf-8", newline="") as f:
        f.write(content)
    print("wrote %s" % rel(path))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="只校验，不写文件")
    args = parser.parse_args()
    try:
        mgmt = management_entries()
        cap = capability_entries()
        table_keys = {e[0] for e in mgmt} | {e[0] for e in cap}
        exempt = exempt_entries(table_keys)
        check_unique(mgmt, lambda e: e[0], "management")
        check_unique(cap, lambda e: e[0], "capability")
        check_unique(exempt, lambda e: e[0], "exempt")
        uncovered = route_map_keys() - table_keys - {e[0] for e in exempt}
        if uncovered:
            for k in sorted(uncovered):
                print("route-map key neither mapped nor exempt: %s" % k)
            return 1
        for e in mgmt:
            if not e[2]:
                raise ValueError("management entry without code: %s" % e[0])
        for e in cap:
            if not e[1]:
                raise ValueError("capability entry without code: %s" % e[0])
        conflicts = cross_table_conflicts(mgmt, cap)
        if conflicts:
            for key, a, b in conflicts:
                print("cross-table conflict: %s -> management=%s capability=%s" % (key, a, b))
            return 1
        sync(MANAGEMENT_GO, render_management(mgmt), args.check)
        sync(CAPABILITY_GO, render_capability(cap), args.check)
        sync(EXEMPT_GO, render_exempt(exempt), args.check)
        overlap = len({e[0] for e in mgmt} & {e[0] for e in cap})
        print("OK: management=%d capability=%d exempt=%d overlap=%d（码一致）"
              % (len(mgmt), len(cap), len(exempt), overlap))
        return 0
    except ValueError as exc:
        print("FAIL: %s" % exc)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
